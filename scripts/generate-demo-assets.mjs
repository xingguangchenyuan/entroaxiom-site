async function makePng(name, svg) {
  await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(join(outDir, name));
}

/* ---------- 极简但合法的 PDF（手工构造，xref 偏移按实际字节计算） ---------- */

function makePdf() {
  const lines = [];
  const objects = [];
  const header = '%PDF-1.4\n';
  const headerLen = Buffer.byteLength(header, 'utf-8');
  let offset = headerLen;

  function pushObject(body) {
    const start = offset;
    objects.push([start, body]);
    lines.push(`${objects.length} 0 obj`);
    lines.push(body);
    lines.push('endobj');
    // 当前 body 总字节 = header + 已写行(含换行) + 末尾换行
    offset = headerLen + Buffer.byteLength(lines.join('\n'), 'utf-8') + 1;
  }

  const content =
    'BT /F1 24 Tf 72 720 Td (Demo guide PDF) Tj ET\n' +
    'BT /F1 12 Tf 72 690 Td (A minimal PDF generated by entroaxiom.) Tj ET\n' +
    'BT /F1 12 Tf 72 666 Td (Purpose: exercise the PDF preview in the file library.) Tj ET';

  pushObject('<< /Type /Catalog /Pages 2 0 R >>');
  pushObject('<< /Type /Pages /Kids [3 0 R] /Count 1 >>');
  pushObject(
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R ' +
      '/Resources << /Font << /F1 5 0 R >> >> >>',
  );
  pushObject(`<< /Length ${Buffer.byteLength(content, 'utf-8')} >>\nstream\n${content}\nendstream`);
  pushObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');

  const body = header + lines.join('\n') + '\n';
  const xrefStart = Buffer.byteLength(body, 'utf-8');

  const entries = objects
    .map(([start]) => `${String(start).padStart(10, '0')} 00000 n`)
    .join('\n');
  const xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${entries}\n`;
  const trailer = `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(body + xref + trailer, 'utf-8');
}

/* ---------- 极简 ZIP 写入器（DEFLATE，纯 Node 实现） ---------- */

function makeZip(entries) {
  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const { name, data } of entries) {
    const nameBuf = Buffer.from(name, 'utf-8');
    const crc = crc32(data) >>> 0;
    const compressed = deflateRawSync(data, { level: 9 });
    const size = compressed.length;

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 名称
    local.writeUInt16LE(8, 8); // DEFLATE
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(size, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    localParts.push(local, nameBuf, compressed);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4); // version made by
    central.writeUInt16LE(20, 6); // version needed
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(size, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(offset, 42);
    centralParts.push(central, nameBuf);

    offset += 30 + nameBuf.length + compressed.length;
  }

  const centralBuf = Buffer.concat(centralParts);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(entries.length, 8);
  eocd.writeUInt16LE(entries.length, 10);
  eocd.writeUInt32LE(centralBuf.length, 12);
  eocd.writeUInt32LE(offset, 16);

  return Buffer.concat([...localParts, centralBuf, eocd]);
}

/* ---------- 组装 ---------- */

async function main() {
  await makePng('demo-image-1.png', svgGrid());
  await makePng('demo-image-2.png', svgRings());
  await makePng('demo-photo.png', svgPhoto());

  writeFileSync(join(outDir, 'demo-guide.pdf'), makePdf());

  const zipEntries = [
    { name: 'demo-notes/readme.txt', data: Buffer.from('装入演示资源的示例文件。\n', 'utf-8') },
    { name: 'demo-notes/links.txt', data: Buffer.from('https://example.com\n', 'utf-8') },
  ];
  writeFileSync(join(outDir, 'demo-archive.zip'), makeZip(zipEntries));

  const docxParts = [
    {
      name: '[Content_Types].xml',
      data: Buffer.from(
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
          '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' +
          '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
          '<Default Extension="xml" ContentType="application/xml"/>' +
          '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>' +
          '</Types>',
        'utf-8',
      ),
    },
    {
      name: '_rels/.rels',
      data: Buffer.from(
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
          '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' +
          '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>' +
          '</Relationships>',
        'utf-8',
      ),
    },
    {
      name: 'word/document.xml',
      data: Buffer.from(
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
          '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">' +
          '<w:body><w:p><w:r><w:t>Demo report (minimal DOCX).</w:t></w:r></w:p></w:body></w:document>',
        'utf-8',
      ),
    },
  ];
  writeFileSync(join(outDir, 'demo-report.docx'), makeZip(docxParts));

  const longName = '2024年度项目学习材料整理清单与进度跟踪备份_最终版_勿删.txt';
  writeFileSync(
    join(outDir, longName),
    Buffer.from('演示用长文件名文本文件：\n用于测试资料库中文件名过长时的截断与省略号显示。\n', 'utf-8'),
  );

  // 打印真实字节数，供回填 demo/files.ts
  const names = ['demo-photo.png', 'demo-guide.pdf', 'demo-archive.zip', 'demo-report.docx', longName];
  const sizes = {};
  for (const n of names) sizes[n] = readFileSync(join(outDir, n)).length;
  console.log(JSON.stringify(sizes, null, 2));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});